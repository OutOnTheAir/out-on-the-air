const BY_CODE = new Map<string, DxccEntity>(DXCC_ENTITIES.map(e => [e.code, e]))

export function dxccName(code: string): string {
  return BY_CODE.get(code)?.name ?? `DXCC ${code}`
}

// Normalizes one DXCC value from any source (ADIF tag, comma list item)
// to a plain integer string. Returns null for blank, zero, or junk values.
export function normalizeDxcc(value: unknown): string | null {
  if (value === null || value === undefined) return null
  const n = parseInt(String(value).trim(), 10)
  if (isNaN(n) || n <= 0) return null
  return String(n)
}

// Splits a stored comma-separated DXCC list into normalized codes.
export function parseDxccList(value: string | null | undefined): string[] {
  if (!value) return []
  const out: string[] = []
  for (const part of value.split(',')) {
    const code = normalizeDxcc(part)
    if (code) out.push(code)
  }
  return out
}
